import type { Roadmap } from "../types";

export function roadmapToMarkdown(roadmap: Roadmap): string {
  const lines: string[] = [];

  lines.push(`# ${roadmap.title}`);
  lines.push("");
  lines.push(roadmap.summary);
  lines.push("");
  lines.push(`**Target Role:** ${roadmap.targetRole}`);
  lines.push(`**Total Duration:** ${roadmap.totalDuration}`);
  lines.push(`**Weekly Hours:** ${roadmap.weeklyHours}`);
  lines.push("");

  lines.push("---");
  lines.push("");

  roadmap.phases.forEach((phase, i) => {
    lines.push(`## Phase ${i + 1}: ${phase.title}`);
    lines.push(`_${phase.duration}_`);
    lines.push("");
    lines.push(`**Goal:** ${phase.goal}`);
    lines.push("");

    lines.push("**Skills to build:**");
    phase.skills.forEach((s) => lines.push(`- ${s}`));
    lines.push("");

    lines.push("**Projects:**");
    phase.projects.forEach((p) => {
      lines.push(`- **${p.title}** — ${p.description}`);
    });
    lines.push("");

    lines.push("**Resources:**");
    phase.resources.forEach((r) => {
      lines.push(`- ${r.title} _(${r.type})_ — ${r.note}`);
    });
    lines.push("");

    lines.push(`**Milestone:** ${phase.milestone}`);
    lines.push("");
    lines.push("---");
    lines.push("");
  });

  if (roadmap.interviewPrep.length > 0) {
    lines.push("## Interview Preparation");
    roadmap.interviewPrep.forEach((item) => lines.push(`- ${item}`));
    lines.push("");
  }

  if (roadmap.certifications.length > 0) {
    lines.push("## Certifications");
    roadmap.certifications.forEach((c) => lines.push(`- ${c}`));
    lines.push("");
  }

  lines.push("## Honest Note");
  lines.push(roadmap.honestNote);
  lines.push("");
  lines.push("---");
  lines.push("_Generated by Waypoint — a career roadmap guide for engineering students._");

  return lines.join("\n");
}

export function downloadMarkdown(roadmap: Roadmap): void {
  const md = roadmapToMarkdown(roadmap);
  const blob = new Blob([md], { type: "text/markdown" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${roadmap.targetRole.replace(/\s+/g, "-").toLowerCase()}-roadmap.md`;
  a.click();
  URL.revokeObjectURL(url);
}
